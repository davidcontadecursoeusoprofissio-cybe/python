semaforo = "verde"

if semaforo == "vermelho" :
    print("🔴PROIBIDO")
    print ("Proibido passagem.")
    
elif semaforo == "amarelo":
    print("🟡ATENÇÃO")
    print("Por favor, atenção na hora de passar.")
    
elif semaforo == "verde" :
    print("🟢passagem")
    print("Passagem liberada")
    
else:
    print("Cor de semáforo inválida!")
    
    print(f"Estado do semaforo: {semaforo}.")
